// Bundles the Plugin API shim (mcp/sandboxEntry.ts) into one script and writes it to mcp/sandbox.generated.ts as a
// string, which sandbox.ts evaluates inside QuickJS. Run after changing mcp/figmaApi.ts or anything in shared/ it uses
// (npm run build:mcp does it for you).
import { build } from 'esbuild'
import { writeFileSync } from 'node:fs'

const out = await build({ entryPoints: ['mcp/sandboxEntry.ts'], bundle: true, format: 'iife', platform: 'neutral', target: 'es2020', minify: true, write: false, legalComments: 'none' })
const source = out.outputFiles[0].text
writeFileSync('mcp/sandbox.generated.ts', `// Generated by scripts/build-sandbox.mjs from mcp/sandboxEntry.ts. Do not edit.\nexport const SANDBOX_SOURCE = ${JSON.stringify(source)}\n`)
console.log(`sandbox bundle: ${(source.length / 1024).toFixed(1)} kB`)
