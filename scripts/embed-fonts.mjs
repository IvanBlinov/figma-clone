// Writes mcp/fonts.generated.ts: Inter (regular and bold) as base64, so PNG exports have a font on servers
// that have none installed. Run after changing the list:   node scripts/embed-fonts.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const dir = 'node_modules/@expo-google-fonts/inter'
const files = { 'Inter-Regular.ttf': '400Regular/Inter_400Regular.ttf', 'Inter-Bold.ttf': '700Bold/Inter_700Bold.ttf' }
const body = Object.entries(files)
  .map(([name, path]) => `  ${JSON.stringify(name)}:\n    ${JSON.stringify(readFileSync(`${dir}/${path}`).toString('base64'))},`)
  .join('\n')
writeFileSync('mcp/fonts.generated.ts', `// Generated by scripts/embed-fonts.mjs. Inter is licensed under the SIL Open Font License 1.1.\nexport const FONTS: Record<string, string> = {\n${body}\n}\n`)
console.log('written')
